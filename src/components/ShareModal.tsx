import React, { useState } from 'react';
import {
  X,
  Share2,
  Copy,
  Check,
  Sparkles,
  ExternalLink,
} from 'lucide-react';
import { Clip } from '../types.ts';

interface ShareModalProps {
  clip: Clip;
  onClose: () => void;
  onShowToast: (msg: string) => void;
}

export const ShareModal: React.FC<ShareModalProps> = ({
  clip,
  onClose,
  onShowToast,
}) => {
  const [copiedLink, setCopiedLink] = useState(false);
  const [copiedCopy, setCopiedCopy] = useState(false);

  const viralCopy = `${clip.title} 🔥\n\n¿Qué opinas sobre esto? Déjame tu comentario abajo 👇\n\n#Shorts #Reels #TikTok #ViralVideo #ClipPulse #CreadoresDeContenido #IA`;
  const shareUrl = window.location.href;

  const handleCopyLink = () => {
    navigator.clipboard.writeText(shareUrl);
    setCopiedLink(true);
    onShowToast('¡Enlace del clip copiado al portapapeles!');
    setTimeout(() => setCopiedLink(false), 2000);
  };

  const handleCopyText = () => {
    navigator.clipboard.writeText(viralCopy);
    setCopiedCopy(true);
    onShowToast('¡Descripción y hashtags copiados!');
    setTimeout(() => setCopiedCopy(false), 2000);
  };

  const platforms = [
    {
      name: 'TikTok',
      color: 'hover:bg-zinc-800 text-white border-zinc-700',
      action: () => window.open('https://www.tiktok.com/upload', '_blank'),
    },
    {
      name: 'YouTube Shorts',
      color: 'hover:bg-red-950/40 text-red-300 border-red-500/30',
      action: () => window.open('https://studio.youtube.com', '_blank'),
    },
    {
      name: 'Instagram Reels',
      color: 'hover:bg-pink-950/40 text-pink-300 border-pink-500/30',
      action: () => window.open('https://www.instagram.com', '_blank'),
    },
    {
      name: 'LinkedIn Video',
      color: 'hover:bg-blue-950/40 text-blue-300 border-blue-500/30',
      action: () => window.open('https://www.linkedin.com', '_blank'),
    },
  ];

  return (
    <div className="fixed inset-0 z-50 bg-black/85 backdrop-blur-xl flex items-center justify-center p-4">
      <div className="relative w-full max-w-lg rounded-3xl bg-zinc-950 border border-purple-500/40 p-6 shadow-2xl shadow-purple-600/20 overflow-hidden text-left glow-purple">
        <div className="flex items-center justify-between border-b border-zinc-800 pb-4 mb-5">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-xl bg-purple-600/20 border border-purple-500/30 flex items-center justify-center">
              <Share2 className="w-4 h-4 text-purple-400" />
            </div>
            <div>
              <h3 className="text-base font-extrabold text-white">Compartir en Redes Sociales</h3>
              <p className="text-[11px] text-zinc-400">Publica o copia el texto viral generado por IA</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-zinc-400 hover:text-white hover:bg-zinc-800 transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Platforms row */}
        <div className="space-y-3 mb-5">
          <label className="text-xs font-semibold text-zinc-300 block">
            Publicación Rápida
          </label>
          <div className="grid grid-cols-2 gap-2.5">
            {platforms.map((p) => (
              <button
                key={p.name}
                onClick={p.action}
                className={`flex items-center justify-between p-3 rounded-2xl border bg-zinc-900/60 text-xs font-bold transition-all ${p.color}`}
              >
                <span>{p.name}</span>
                <ExternalLink className="w-3.5 h-3.5 opacity-60" />
              </button>
            ))}
          </div>
        </div>

        {/* Viral copy generated by AI */}
        <div className="space-y-2 mb-5">
          <div className="flex items-center justify-between">
            <label className="text-xs font-bold text-zinc-300 flex items-center gap-1.5">
              <Sparkles className="w-3.5 h-3.5 text-purple-400" />
              Copywriting y Hashtags Virales (IA)
            </label>
            <button
              onClick={handleCopyText}
              className="text-xs font-semibold text-purple-400 hover:text-purple-300 flex items-center gap-1 transition-colors"
            >
              {copiedCopy ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copiedCopy ? 'Copiado' : 'Copiar Texto'}</span>
            </button>
          </div>
          <div className="p-3.5 rounded-2xl bg-zinc-900/70 border border-zinc-800 text-xs text-zinc-300 font-mono whitespace-pre-wrap leading-relaxed max-h-36 overflow-y-auto">
            {viralCopy}
          </div>
        </div>

        {/* Link copy */}
        <div className="flex items-center gap-2 p-2 rounded-2xl bg-zinc-900/60 border border-zinc-800">
          <input
            type="text"
            readOnly
            value={shareUrl}
            className="bg-transparent text-xs text-zinc-400 font-mono px-2 flex-1 focus:outline-none"
          />
          <button
            onClick={handleCopyLink}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-purple-600 hover:bg-purple-500 text-white font-bold text-xs transition-colors shrink-0"
          >
            {copiedLink ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copiedLink ? 'Copiado' : 'Copiar Link'}</span>
          </button>
        </div>
      </div>
    </div>
  );
};
